"""Build the dashboard dataset from the cost-tracking workbook.

Reads the first sheet of the workbook (one row per manufacturing order), keeps
only orders that have both revenue and production cost, drops identifying
columns (lot numbers, part numbers, product names), recomputes the financial
metrics and writes:

  data/orders.csv      tidy table, one row per manufacturing order (MO)
  assets/data.js       the same rows for the static dashboard (window.DASH_DATA)

Usage:
  python scripts/prepare_data.py path/to/workbook.xlsx [--scale 0.8]

--scale multiplies every money column by a constant. Margins, tiers and trends
are unchanged, so the project can be published without real dollar values.
"""
import argparse
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]

# Source columns, by column letter in the workbook's first sheet.
COLUMNS = {
    "A": "production_end_date",
    "B": "mo",
    "E": "client",
    "G": "product",
    "H": "semi_finished",
    "I": "sf_units",
    "J": "finished_good",
    "K": "fg_units",
    "L": "shipping_date",
    "M": "shipping_units",
    "N": "unit_price",        # sales price per unit
    "P": "unit_cost",         # ERP production cost per unit
    "S": "revenue",
    "T": "mo_cost",
    "W": "monthly_fixed_cost",
    "Y": "target_margin",
}
MONEY = ["unit_price", "unit_cost", "revenue", "mo_cost", "monthly_fixed_cost"]


def col_index(letter: str) -> int:
    n = 0
    for ch in letter:
        n = n * 26 + (ord(ch.upper()) - 64)
    return n - 1


def tier(gm: float) -> str:
    if gm > 0.30:
        return "Highly profitable"
    if gm >= 0:
        return "Moderate margin"
    return "Unprofitable"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("workbook")
    ap.add_argument("--scale", type=float, default=1.0)
    args = ap.parse_args()

    raw = pd.read_excel(args.workbook, sheet_name=0)
    df = pd.DataFrame({name: raw.iloc[:, col_index(letter)] for letter, name in COLUMNS.items()})

    df = df[pd.to_numeric(df["revenue"], errors="coerce").notna()
            & pd.to_numeric(df["mo_cost"], errors="coerce").notna()].copy()
    for col in ["production_end_date", "shipping_date"]:
        df[col] = pd.to_datetime(df[col], errors="coerce").dt.strftime("%Y-%m-%d")
    for col in ["sf_units", "fg_units", "shipping_units", "mo"]:
        df[col] = pd.to_numeric(df[col], errors="coerce").round().astype("Int64")
    for col in MONEY + ["target_margin"]:
        df[col] = pd.to_numeric(df[col], errors="coerce")
    for col in MONEY:
        df[col] = df[col] * args.scale
    for col in ["client", "product", "semi_finished", "finished_good"]:
        df[col] = df[col].astype(str).str.strip()

    df["gross_profit"] = df["revenue"] - df["mo_cost"]
    df["gross_margin"] = df["gross_profit"] / df["revenue"]
    df["margin_tier"] = df["gross_margin"].map(tier)
    df = df.sort_values(["production_end_date", "mo"]).reset_index(drop=True)

    (ROOT / "data").mkdir(exist_ok=True)
    df.to_csv(ROOT / "data" / "orders.csv", index=False, float_format="%.6f")

    rows = json.loads(df.to_json(orient="records", double_precision=6))
    js = "// Generated by scripts/prepare_data.py. Do not edit by hand.\n"
    js += "window.DASH_DATA = " + json.dumps(rows, separators=(",", ":")) + ";\n"
    (ROOT / "assets" / "data.js").write_text(js)

    print(f"{len(df)} manufacturing orders, "
          f"{df['production_end_date'].min()} to {df['production_end_date'].max()}")
    print(f"Revenue {df['revenue'].sum():,.2f}  Cost {df['mo_cost'].sum():,.2f}  "
          f"GM {df['gross_profit'].sum() / df['revenue'].sum():.1%}")


if __name__ == "__main__":
    main()
